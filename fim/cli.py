"""Command-line interface (git-style subcommands).

Exit codes: 0 clean, 1 changes found, 2 CRITICAL changes found,
3 error / integrity (HMAC) failure.
"""

import argparse
import os
import sys

import yaml

from . import __version__
from .alerts import emit
from .config import WatchPath, load_config
from .errors import ConfigError, FimError, IntegrityError
from .hashing import SUPPORTED_ALGORITHMS
from .monitor import Monitor
from .response import quarantine
from .severity import CRITICAL
from .watch import watch

EXIT_OK, EXIT_CHANGES, EXIT_CRITICAL, EXIT_ERROR = 0, 1, 2, 3


def exit_code_for(alerts):
    if any(a.severity == CRITICAL for a in alerts):
        return EXIT_CRITICAL
    return EXIT_CHANGES if alerts else EXIT_OK


def build_parser():
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--config", "-c", default="fim.yaml", help="config file (default: fim.yaml)")

    fmt = argparse.ArgumentParser(add_help=False)
    fmt.add_argument("--format", choices=("text", "json"), default="text",
                     help="alert output format; 'json' emits one JSON object per line")

    resp = argparse.ArgumentParser(add_help=False)
    resp.add_argument("--enable-response", action="store_true",
                      help="OPT-IN: move files behind CRITICAL alerts into the quarantine dir")
    resp.add_argument("--full-hash", action="store_true",
                      help="disable the mtime/size pre-filter and re-hash every file")

    p = argparse.ArgumentParser(prog="fim", description="File Integrity Monitor")
    p.add_argument("--version", action="version", version="fim " + __version__)
    sub = p.add_subparsers(dest="command", required=True, metavar="{init,scan,watch,diff,snapshots}")

    s = sub.add_parser("init", parents=[common], help="create the signed baseline")
    s.add_argument("--path", "-p", action="append", default=[], metavar="DIR",
                   help="directory/file to monitor (repeatable); overrides 'paths' in the config")
    s.add_argument("--algorithm", choices=SUPPORTED_ALGORITHMS, help="hash algorithm (default: config / sha256)")
    s.add_argument("--force", action="store_true", help="replace an existing baseline")

    s = sub.add_parser("scan", parents=[common, fmt, resp], help="one-shot compare against the baseline")
    s.add_argument("--update-baseline", action="store_true",
                   help="after reporting, accept the current state as the new baseline")

    s = sub.add_parser("watch", parents=[common, fmt, resp], help="continuously monitor")
    s.add_argument("--interval", type=float, help="seconds between scans (default: config, 30)")
    s.add_argument("--mode", choices=("poll", "events"), default="poll",
                   help="poll (default, no extra deps) or events (needs watchdog)")
    s.add_argument("--max-scans", type=int, default=None, help=argparse.SUPPRESS)

    s = sub.add_parser("diff", parents=[common, fmt], help="compare two stored snapshots")
    s.add_argument("snapshot_1", help="older snapshot id (or 'baseline')")
    s.add_argument("snapshot_2", help="newer snapshot id (or 'baseline')")

    sub.add_parser("snapshots", parents=[common], help="list stored snapshots")
    return p


def cmd_init(args, out, err):
    # A missing config is fine for init (we can create one); a broken one is not.
    cfg = load_config(args.config) if os.path.exists(args.config) else None
    if args.path:
        paths = [WatchPath(path=_abs(p)) for p in args.path]
        if cfg is None:
            _write_config(args.config, args.path, args.algorithm)
            cfg = load_config(args.config)
            print("created %s" % args.config, file=err)
        else:
            cfg.paths = paths
    elif cfg is None:
        raise ConfigError("config file not found: %s (pass --path DIR to create one)" % args.config)
    doc, stats, key_created = Monitor(cfg).init(cfg.paths, args.algorithm, args.force)
    print("baseline created: %d files, algorithm %s, snapshot %s"
          % (len(doc["files"]), doc["algorithm"], doc["id"]), file=out)
    print("state dir: %s" % cfg.state_dir, file=err)
    print("HMAC key %s: %s  (keep it OUT of git and away from the monitored paths)"
          % ("generated" if key_created else "reused", cfg.key_file), file=err)
    for w in stats.warnings:
        print("warning: " + w, file=err)
    return EXIT_OK


def _abs(p):
    return os.path.abspath(os.path.expanduser(p))


def _write_config(path, paths, algorithm):
    data = {"paths": [_abs(p) for p in paths]}
    if algorithm:
        data["hash_algorithm"] = algorithm
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("# generated by 'fim init'; see fim.example.yaml for all options\n")
        yaml.safe_dump(data, fh, sort_keys=False)


def cmd_scan(args, out, err):
    cfg = load_config(args.config)
    mon = Monitor(cfg)
    result = mon.scan(full_hash=args.full_hash)
    for w in result.stats.warnings:
        print("warning: " + w, file=err)
    emit(result.alerts, out, args.format, cfg.log_file)
    if mon.should_snapshot(result):
        sid = mon.save_snapshot(result)
        print("snapshot saved: %s" % sid, file=err)
    if args.enable_response:
        for a in result.alerts:
            quarantine(a, cfg.quarantine_dir, cfg.log_file, err)
    st = result.stats
    print("scanned %d files (%d hashed, %d reused via mtime/size); %d change(s)"
          % (st.files, st.hashed, st.reused, len(result.alerts)), file=err)
    if args.update_baseline:
        sid = mon.accept(result)
        print("baseline updated: %s" % sid, file=err)
    return exit_code_for(result.alerts)


def cmd_watch(args, out, err):
    cfg = load_config(args.config)
    interval = args.interval if args.interval is not None else cfg.interval
    print("watching (%s mode, every %gs); Ctrl+C to stop" % (args.mode, interval), file=err)
    alerts = watch(Monitor(cfg), out, err, interval=interval, mode=args.mode, fmt=args.format,
                   enable_response=args.enable_response, full_hash=args.full_hash,
                   max_scans=args.max_scans)
    return exit_code_for(alerts)


def cmd_diff(args, out, err):
    cfg = load_config(args.config)
    a, b, alerts = Monitor(cfg).diff(args.snapshot_1, args.snapshot_2)
    print("comparing %s (%s) -> %s (%s)" % (a["id"], a["created"], b["id"], b["created"]), file=err)
    emit(alerts, out, args.format, None)
    print("%d difference(s)" % len(alerts), file=err)
    return exit_code_for(alerts)


def cmd_snapshots(args, out, err):
    cfg = load_config(args.config)
    store = Monitor(cfg).store
    for sid in store.list_ids():
        doc = store.load(sid)
        print("%-24s %-9s %s  %d files" % (sid, doc["kind"], doc["created"], len(doc["files"])), file=out)
    return EXIT_OK


COMMANDS = {"init": cmd_init, "scan": cmd_scan, "watch": cmd_watch,
            "diff": cmd_diff, "snapshots": cmd_snapshots}


def main(argv=None, out=None, err=None):
    out = out or sys.stdout
    err = err or sys.stderr
    for stream in (out, err):
        try:  # never crash on odd characters in file names
            stream.reconfigure(errors="backslashreplace")
        except Exception:
            pass
    args = build_parser().parse_args(argv)
    try:
        return COMMANDS[args.command](args, out, err)
    except IntegrityError as exc:
        print("!!! INTEGRITY FAILURE: %s" % exc, file=err)
        print("!!! Do not trust this baseline. Investigate before re-running 'fim init'.", file=err)
        return EXIT_ERROR
    except FimError as exc:
        print("error: %s" % exc, file=err)
        return EXIT_ERROR


if __name__ == "__main__":
    sys.exit(main())
